import { AssessmentResult, CATEGORY_LABELS, Category } from "./types";
import { SEVERITY_LABEL, readinessLabel } from "./scoring";

export function resultToMarkdown(customerName: string, result: AssessmentResult): string {
  const lines: string[] = [];
  const name = customerName.trim() || "Unnamed Customer";

  lines.push(`# Deployment Readiness Report — ${name}`);
  lines.push("");
  lines.push(`**Readiness score:** ${result.score}/100 (${readinessLabel(result.score)})`);
  lines.push("");
  lines.push(
    `**Findings:** ${result.findings.length} total — ${result.severityCounts.critical} critical, ${result.severityCounts.high} high, ${result.severityCounts.medium} medium, ${result.severityCounts.low} low`
  );
  lines.push("");

  const categories = Object.keys(CATEGORY_LABELS) as Category[];
  for (const cat of categories) {
    const items = result.findings.filter((f) => f.category === cat);
    if (items.length === 0) continue;
    lines.push(`## ${CATEGORY_LABELS[cat]}`);
    lines.push("");
    for (const f of items) {
      lines.push(`### [${SEVERITY_LABEL[f.severity]}] ${f.title}`);
      lines.push("");
      lines.push(f.explanation);
      lines.push("");
      if (f.validationSteps.length) {
        lines.push("**Validation steps:**");
        for (const s of f.validationSteps) lines.push(`- ${s}`);
        lines.push("");
      }
      if (f.fdeQuestions.length) {
        lines.push("**Questions to ask the customer:**");
        for (const q of f.fdeQuestions) lines.push(`- ${q}`);
        lines.push("");
      }
    }
  }

  lines.push("---");
  lines.push("_Generated by the Meticulous Deployment Readiness Assessor._");

  return lines.join("\n");
}
